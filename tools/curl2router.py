#!/usr/bin/env python3
"""Convert a browser-captured cURL (bash format) into a router-side shell script.

WHY
    Community consensus for Ruijie ePortal: do NOT rebuild the request -- replay
    the exact request the browser made successfully. It already carries the
    correct opaque queryString tokens and headers.

    This tool turns that captured command into something you can drop straight
    onto a busybox router (ASCII only, LF line endings, sh -n clean).

USAGE
    python3 curl2router.py captured-curl.txt
    python3 curl2router.py            # then paste and press Ctrl-D / Ctrl-Z

OUTPUT
    campus-curl.sh      runnable on the router
    campus-params.txt   human-readable summary of what was parsed
"""
import os
import re
import shlex
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_SH = os.path.join(HERE, "campus-curl.sh")
OUT_TXT = os.path.join(HERE, "campus-params.txt")


def read_input():
    if len(sys.argv) > 1:
        if sys.argv[1] in ("-h", "--help"):
            print(__doc__)
            sys.exit(0)
        with open(sys.argv[1], encoding="utf-8", errors="replace") as fh:
            return fh.read()
    print("Paste the browser's 'Copy as cURL (bash)' content, then Ctrl-D / Ctrl-Z:")
    print("(or pass a filename as the first argument; --help for details)")
    print()
    return sys.stdin.read()


def parse_curl(text):
    # join line continuations (bash uses backslash, cmd.exe uses caret)
    t = text.replace("^\r\n", " ").replace("^\n", " ")
    t = t.replace("\\\r\n", " ").replace("\\\n", " ")
    t = re.sub(r"\s+", " ", t).strip()
    t = re.sub(r"^curl(\.exe)?\s+", "", t, flags=re.I)

    url, headers, data, method = "", [], "", "POST"

    try:
        toks = shlex.split(t)
    except ValueError:
        toks = [x.strip("'\"") for x in re.findall(r"""(?:'[^']*'|"[^"]*"|\S+)""", t)]

    i = 0
    while i < len(toks):
        tk = toks[i]
        low = tk.lower()
        if low in ("-h", "--header") and i + 1 < len(toks):
            headers.append(toks[i + 1])
            i += 2
            continue
        if low in ("--data-raw", "--data", "-d", "--data-binary", "--data-urlencode") and i + 1 < len(toks):
            data = toks[i + 1]
            i += 2
            continue
        if low in ("-x", "--request") and i + 1 < len(toks):
            method = toks[i + 1]
            i += 2
            continue
        if low.startswith("http"):
            url = tk
            i += 1
            continue
        if low in ("--compressed", "-k", "--insecure", "-s", "--silent", "-v"):
            i += 1
            continue
        if low.startswith("-"):
            if i + 1 < len(toks) and not toks[i + 1].startswith("-") and "://" not in toks[i + 1]:
                i += 2
            else:
                i += 1
            continue
        i += 1

    if not url:
        m = re.search(r"(https?://[^\s'\"]+)", t)
        if m:
            url = m.group(1)
    if not data:
        m = re.search(r"(?:--data-raw|--data|-d)\s+(['\"])(.*?)\1", t, re.S)
        if m:
            data = m.group(2)
    return {"url": url, "headers": headers, "data": data, "method": method}


def sh_quote(s):
    return "'" + s.replace("'", "'\"'\"'") + "'"


KEEP_HEADERS = ("accept", "content", "origin", "referer", "user-agent", "x-", "cookie")


def build_script(p):
    host = re.sub(r"^https?://", "", p["url"]).split("/")[0].split(":")[0]
    hdr_lines = "\n".join(
        "    -H %s \\" % sh_quote(h)
        for h in p["headers"]
        if h.lower().split(":")[0] in KEEP_HEADERS or h.lower().startswith(("x-",))
    )
    return """#!/bin/sh
# ============================================================================
#  campus-curl.sh  --  replay the exact request captured from the browser
#  auto-generated by curl2router.py at %s
#
#  Community-standard approach: do NOT rebuild the request. Replay the very
#  request the browser made successfully -- it already carries the correct
#  opaque queryString tokens and headers.
#
#  ASCII-only on purpose (busybox + no locale).
# ============================================================================

URL=%s

DATA=%s

req() {
    curl -s -m 20 -X %s \\
    -H 'Host: %s' \\
%s
    --data-raw "$DATA" \\
    "$URL"
}

# online check: ONLY 204 + empty body counts as really online
probe_online() {
    out=$(curl -s -m 12 -w '\\n%%{http_code}' http://connectivitycheck.platform.hicloud.com/generate_204 2>/dev/null)
    code=$(printf '%%s' "$out" | tail -n 1)
    body=$(printf '%%s' "$out" | sed '$d')
    [ "$code" = "204" ] && [ -z "$body" ]
}

log() {
    echo "$(date '+%%Y-%%m-%%d %%H:%%M:%%S') $*" >> /tmp/campus-curl.log
}

log "=== campus-curl started ==="

echo "[campus-curl] replaying captured request ..."
R=$(req)
echo "[campus-curl] response: $R"
log "REPLAY resp=${R}"
case "$R" in
    *'\''"result":"success"'\''*) echo "[campus-curl] OK: auth success" ; log "OK" ;;
    *)                            echo "[campus-curl] FAIL: see response above" ; log "FAIL" ;;
esac

sleep 4
if probe_online; then
    echo "[campus-curl] confirmed ONLINE"
else
    echo "[campus-curl] still NOT online"
fi
""" % (time.strftime("%Y-%m-%d %H:%M:%S"), sh_quote(p["url"]),
       sh_quote(p["data"]), p["method"], host, hdr_lines)


def main():
    text = read_input()
    if not text.strip():
        print("no input")
        return 1
    p = parse_curl(text)

    print()
    print("=" * 70)
    print(" parsed")
    print("=" * 70)
    print("  URL    : %s" % p["url"])
    print("  method : %s" % p["method"])
    print("  form fields:")
    for kv in p["data"].split("&"):
        if "=" in kv:
            k, v = kv.split("=", 1)
            print("      %-18s = %s" % (k, v[:90]))
        elif kv:
            print("      %s" % kv[:90])
    print("  headers (%d):" % len(p["headers"]))
    for h in p["headers"]:
        print("      %s" % h[:110])

    with open(OUT_TXT, "w", encoding="utf-8") as fh:
        fh.write("URL: %s\nMETHOD: %s\n\nHEADERS:\n" % (p["url"], p["method"]))
        for h in p["headers"]:
            fh.write("  %s\n" % h)
        fh.write("\nDATA:\n")
        for kv in p["data"].split("&"):
            fh.write("  %s\n" % kv)

    script = build_script(p)
    with open(OUT_SH, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(script)

    print()
    print("  written: %s" % OUT_SH)
    print("  written: %s" % OUT_TXT)
    print()
    print("  deploy to the router:")
    print('    cat campus-curl.sh | ssh root@ROUTER "cat > /tmp/campus-curl.sh"')
    print('    ssh root@ROUTER "sh /tmp/campus-curl.sh"')
    return 0


if __name__ == "__main__":
    sys.exit(main())
